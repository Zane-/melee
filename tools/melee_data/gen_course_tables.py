#!/usr/bin/env python3
"""Generate the frame data table the course engine compiles in.

    python tools/melee_data/gen_course_tables.py [--check]

Reads data/framedata/<id>.json (from extract.py) and writes
src/tmce/events/course/gen/framedata.inc.h: per fighter (indexed by the
game's internal fighter kind, FighterData.kind) the jump squat and, per
move, first hit frame, first actionable frame, total frames, landing lag
and damage. Drills and guides read numbers from it instead of typing them
in. --check exits 1 if the file on disk is out of date.
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import calc  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))))
OUT = os.path.join(REPO, "src/tmce/events/course/gen/framedata.inc.h")

# Internal fighter kinds (FTKIND_* in MexTK, FighterKind in the decomp), in
# order. Nana uses Popo's data.
INTERNAL = [
    "mario", "fox", "captain-falcon", "donkey-kong", "kirby", "bowser",
    "link", "sheik", "ness", "peach", "ice-climbers", "ice-climbers",
    "pikachu", "samus", "yoshi", "jigglypuff", "mewtwo", "luigi", "marth",
    "zelda", "young-link", "dr-mario", "falco", "pichu",
    "mr-game-and-watch", "ganondorf", "roy",
]

# (enum name, key in the JSON's "moves")
MOVES = [
    ("JAB1", "jab1"), ("DASH_ATTACK", "dash_attack"), ("FTILT", "ftilt"),
    ("UTILT", "utilt"), ("DTILT", "dtilt"), ("FSMASH", "fsmash"),
    ("USMASH", "usmash"), ("DSMASH", "dsmash"), ("NAIR", "nair"),
    ("FAIR", "fair"), ("BAIR", "bair"), ("UAIR", "uair"), ("DAIR", "dair"),
    ("GRAB", "grab"), ("DASH_GRAB", "dash_grab"), ("SPOTDODGE", "spotdodge"),
    ("ROLL_FORWARD", "roll_forward"), ("ROLL_BACKWARD", "roll_backward"),
    ("AIRDODGE", "airdodge"), ("TECH_IN_PLACE", "tech_in_place"),
    ("TECH_ROLL_FORWARD", "tech_roll_forward"),
    ("TECH_ROLL_BACKWARD", "tech_roll_backward"),
    ("LEDGE_GETUP", "ledge_getup"), ("LEDGE_ROLL", "ledge_roll"),
]


def generate():
    out = [
        "/*",
        " * Generated by tools/melee_data/gen_course_tables.py from",
        " * data/framedata/*.json (the game's own fighter files). Do not edit:",
        " * change the data or the generator and run it again.",
        " *",
        " * Frames are 1-indexed: hit = first frame a hitbox is out (0 = none),",
        " * faf = first actionable frame, total = animation length. Named",
        " * .inc.h because it is included into event.c (see there).",
        " */",
        "",
        "enum CourseMove {",
    ]
    out += ["    CMOVE_%s," % name for name, _ in MOVES]
    out += [
        "    CMOVE_COUNT,",
        "};",
        "",
        "typedef struct CourseMoveData {",
        "    s16 hit;   ///< first hit frame, 0 = no hitbox",
        "    s16 faf;   ///< first actionable frame",
        "    s16 total; ///< animation length",
        "    s8 land;   ///< aerial landing lag, 0 = not an aerial",
        "    s8 land_l; ///< L-cancelled landing lag",
        "    u8 damage; ///< strongest hitbox",
        "    s8 intang_from, intang_to; ///< intangible frames, 0 = none",
        "} CourseMoveData;",
        "",
        "typedef struct CourseFighterData {",
        "    u8 jump_squat;       ///< frames before airborne",
        "    u8 landing_lag;      ///< normal landing",
        "    u8 weight;",
        "    float jump_v;        ///< full hop initial Y speed",
        "    float hop_v;         ///< short hop initial Y speed",
        "    CourseMoveData move[CMOVE_COUNT];",
        "} CourseFighterData;",
        "",
        "/* Indexed by FighterData.kind (internal fighter kind). */",
        "static const CourseFighterData course_fd[%d] = {" % len(INTERNAL),
    ]
    cache = {}
    for kind, cid in enumerate(INTERNAL):
        if cid not in cache:
            with open(os.path.join(REPO, "data/framedata", cid + ".json")) as f:
                cache[cid] = json.load(f)
        c = cache[cid]
        a = c["attributes"]
        out.append("    /* %2d %s */ { %d, %d, %d, %sF, %sF, {" % (
            kind, cid, a["jump_startup_time"], a["normal_landing_lag"],
            a["weight"], float(a["jump_v_initial_velocity"]),
            float(a["hop_v_initial_velocity"])))
        for name, key in MOVES:
            m = c["moves"].get(key)
            if m is None:
                out.append("        [CMOVE_%s] = { 0 }," % name)
                continue
            dmg = max([b["damage"] for h in m.get("hits", [])
                       for b in h["hitboxes"]] + [0])
            inv = m.get("intangible") or [[0, 0]]
            out.append("        [CMOVE_%s] = { %d, %d, %d, %d, %d, %d, %d, %d },"
                       % (name, m.get("first_hit_frame") or 0, calc.faf(m),
                          m["total_frames"], m.get("landing_lag", 0),
                          m.get("landing_lag_lcancel", 0), min(dmg, 255),
                          inv[0][0], inv[-1][1]))
        out.append("    } },")
    out += ["};", ""]
    return "\n".join(out)


def main():
    text = generate()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == text
        print("up to date" if ok else "OUT OF DATE: run gen_course_tables.py")
        return 0 if ok else 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote", os.path.relpath(OUT, REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
