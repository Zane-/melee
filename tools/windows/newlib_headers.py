#!/usr/bin/env python3
"""Assemble newlib's C library headers for powerpc-none-eabi on Windows.

The DWARF build (cmake/Dwarf.cmake) compiles the game for the console's ABI
and only needs libc *headers*; on Linux they come from Nix's
pkgsCross.ppc-embedded.newlib. Here they come from newlib's source release:
libc/include, the PowerPC machine headers laid over it, and the two headers
newlib's configure step would generate.

Usage: python tools/windows/newlib_headers.py SRC OUT
    SRC: the unpacked newlib-<version> source directory
    OUT: the include directory to create (pass it as NEWLIB_INCLUDE)
"""

import re
import shutil
import sys
from pathlib import Path


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src = Path(sys.argv[1]) / "newlib"
    out = Path(sys.argv[2])
    if not (src / "libc/include/stdio.h").exists():
        sys.exit(f"{src}: not a newlib source tree")
    m = re.search(r"newlib-(\d+)\.(\d+)\.(\d+)", str(Path(sys.argv[1]).name))
    if not m:
        sys.exit("cannot read the newlib version from the source directory")
    major, minor, patch = m.groups()

    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(src / "libc/include", out)
    shutil.copytree(src / "libc/machine/powerpc/machine", out / "machine",
                    dirs_exist_ok=True)

    (out / "_newlib_version.h").write_text(
        "/* Generated by tools/windows/newlib_headers.py. */\n"
        "#ifndef _NEWLIB_VERSION_H__\n#define _NEWLIB_VERSION_H__ 1\n"
        f'#define _NEWLIB_VERSION "{major}.{minor}.{patch}"\n'
        f"#define __NEWLIB__ {major}\n"
        f"#define __NEWLIB_MINOR__ {minor}\n"
        f"#define __NEWLIB_PATCHLEVEL__ {patch}\n"
        "#endif\n")
    # A default configure for powerpc-none-eabi: nothing optional enabled.
    (out / "newlib.h").write_text(
        "/* Generated by tools/windows/newlib_headers.py. */\n"
        "#ifndef __NEWLIB_H__\n#define __NEWLIB_H__ 1\n"
        "#include <_newlib_version.h>\n"
        "#define _WANT_IO_C99_FORMATS 1\n"
        "#define _WANT_IO_LONG_LONG 1\n"
        "#define _WANT_REGISTER_FINI 1\n"
        "#define _MB_LEN_MAX 1\n"
        "#define _HAVE_INITFINI_ARRAY 1\n"
        "#define _ATEXIT_DYNAMIC_ALLOC 1\n"
        "#define _FVWRITE_IN_STREAMIO 1\n"
        "#define _FSEEK_OPTIMIZATION 1\n"
        "#define _UNBUF_STREAM_OPT 1\n"
        "#define _RETARGETABLE_LOCKING 1\n"
        "#endif\n")
    print(f"OK: {out}")


if __name__ == "__main__":
    main()
